/**
 * ESPN last-season STATS importer (the "2026 Stats Board").
 *
 *   node --env-file=.env.local scripts/espn-stats-import.mjs [count]
 *
 * Pulls the top `count` players (default 250) sorted by ESPN's draft ranking and
 * writes lib/data/espn-stats.ts with each player's REAL 2025-26 season actuals:
 *   - totalFpts   season total fantasy points, scored in OUR league (appliedTotal)
 *   - avgFpts     per-game fantasy points (appliedAverage = total / games)
 *   - gp, min, fgPct, ftPct, tpm, reb, ast, stl, blk, to, pts  (per-game)
 *   - ato         assist-to-turnover ratio (derived: ast / to)
 *
 * ESPN calls last season "2026 STATISTICS" in its UI (the season that just
 * finished). Nothing here is projected or guessed — it's what actually happened.
 * Players who didn't play last season (e.g. Haliburton — full-year injury) have
 * no actuals; they're written with hasData:false so the board can flag them
 * rather than silently drop them.
 *
 * Ranks (avgRank, totalRank) are computed across the players who DO have data.
 */
import { writeFileSync, mkdirSync } from 'node:fs';

const COUNT = Number(process.argv[2] ?? 250);
const SEASON = 2026;
const LEAGUE = process.env.ESPN_LEAGUE_ID ?? '803871539';

if (!process.env.ESPN_S2 || !process.env.SWID) {
  console.error('ESPN_S2 / SWID are not set. Run with --env-file=.env.local');
  process.exit(1);
}
const swid = process.env.SWID.startsWith('{') ? process.env.SWID : `{${process.env.SWID}}`;

const S = { PTS: 0, BLK: 1, STL: 2, AST: 3, REB: 6, TO: 11, TPM: 17, FGP: 19, FTP: 20, MIN: 40, GP: 42 };
const POS = { 1: 'PG', 2: 'SG', 3: 'SF', 4: 'PF', 5: 'C' };
const TEAM = {
  1: 'ATL', 2: 'BOS', 3: 'NOP', 4: 'CHI', 5: 'CLE', 6: 'DAL', 7: 'DEN', 8: 'DET',
  9: 'GSW', 10: 'HOU', 11: 'IND', 12: 'LAC', 13: 'LAL', 14: 'MIA', 15: 'MIL',
  16: 'MIN', 17: 'BKN', 18: 'NYK', 19: 'ORL', 20: 'PHI', 21: 'PHX', 22: 'POR',
  23: 'SAC', 24: 'SAS', 25: 'OKC', 26: 'UTA', 27: 'WAS', 28: 'TOR', 29: 'MEM', 30: 'CHA',
};

const url =
  `https://lm-api-reads.fantasy.espn.com/apis/v3/games/fba/seasons/${SEASON}` +
  `/segments/0/leagues/${LEAGUE}?view=kona_player_info`;
const filter = {
  players: { limit: COUNT, sortDraftRanks: { sortPriority: 100, sortAsc: true, value: 'STANDARD' } },
};

const res = await fetch(url, {
  headers: {
    accept: 'application/json',
    'user-agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)',
    'x-fantasy-filter': JSON.stringify(filter),
    'x-fantasy-platform': 'kona',
    'x-fantasy-source': 'kona',
    cookie: `espn_s2=${process.env.ESPN_S2}; SWID=${swid}`,
  },
});
if (!res.ok) {
  console.error(`ESPN returned ${res.status}: ${(await res.text()).slice(0, 300)}`);
  process.exit(1);
}
const payload = await res.json();
const players = payload.players ?? [];
console.log(`Fetched ${players.length} players.`);

const rows = [];
for (const entry of players) {
  const p = entry.player;
  if (!p) continue;

  const actual = (p.stats ?? []).find((s) => s.statSourceId === 0 && s.statSplitTypeId === 0);
  const a = actual?.averageStats;
  const hasData = Boolean(a && actual.appliedTotal > 0 && (a[S.GP] ?? 0) > 0);

  const to = hasData ? round1(a[S.TO]) : 0;
  const ast = hasData ? round1(a[S.AST]) : 0;

  rows.push({
    id: slug(p.fullName, p.id),
    espnId: p.id,
    name: p.fullName,
    team: TEAM[p.proTeamId] ?? '—',
    pos: POS[p.defaultPositionId] ?? 'SF',
    espnRank: p.draftRanksByRankType?.STANDARD?.rank ?? 9999,
    injuryStatus: p.injuryStatus ?? 'ACTIVE',
    hasData,
    totalFpts: hasData ? Math.round(actual.appliedTotal) : 0,
    avgFpts: hasData ? round1(actual.appliedAverage) : 0,
    gp: hasData ? Math.round(a[S.GP]) : 0,
    min: hasData ? round1(a[S.MIN]) : 0,
    fgPct: hasData ? round3(a[S.FGP]) : 0,
    ftPct: hasData ? round3(a[S.FTP]) : 0,
    tpm: hasData ? round1(a[S.TPM]) : 0,
    reb: hasData ? round1(a[S.REB]) : 0,
    ast,
    stl: hasData ? round2(a[S.STL]) : 0,
    blk: hasData ? round2(a[S.BLK]) : 0,
    to,
    pts: hasData ? round1(a[S.PTS]) : 0,
    ato: hasData && to > 0 ? round2(ast / to) : 0,
  });
}

// De-dupe ids.
const seen = new Map();
for (const r of rows) {
  if (seen.has(r.id)) { seen.set(r.id, seen.get(r.id) + 1); r.id = `${r.id}-${seen.get(r.id)}`; }
  else seen.set(r.id, 1);
}

// Rank by avg and by total across players WITH data. No-data players get rank 0.
const withData = rows.filter((r) => r.hasData);
[...withData].sort((x, y) => y.avgFpts - x.avgFpts).forEach((r, i) => (r.avgRank = i + 1));
[...withData].sort((x, y) => y.totalFpts - x.totalFpts).forEach((r, i) => (r.totalRank = i + 1));
for (const r of rows) { r.avgRank = r.avgRank ?? 0; r.totalRank = r.totalRank ?? 0; }

// Default board order: total FPTS desc, no-data players last.
rows.sort((x, y) => (y.totalFpts - x.totalFpts) || x.espnRank - y.espnRank);

const header = `// GENERATED by scripts/espn-stats-import.mjs — do not edit by hand.
// Source: ESPN fantasy API (league ${LEAGUE}, season ${SEASON}). Imported ${new Date().toISOString().slice(0, 10)}.
//
// Real 2025-26 season actuals (ESPN's "2026 STATISTICS"), scored in our league.
// totalFpts/avgFpts are ESPN's own totals for Horn Pub Ligue 1 scoring. Players
// who missed last season have hasData:false. avgRank/totalRank are computed
// across players with data.

import type { StatRow } from '@/lib/draft/stats-board';

export const STAT_ROWS: StatRow[] = ${JSON.stringify(rows, null, 2)};
`;

mkdirSync('lib/data', { recursive: true });
writeFileSync('lib/data/espn-stats.ts', header);

console.log(`Wrote lib/data/espn-stats.ts with ${rows.length} players (${withData.length} with data).`);
console.log('\nTop 15 by total FPTS:');
for (const r of rows.slice(0, 15)) {
  console.log(`  ${String(r.totalRank).padStart(3)}. ${r.name.padEnd(24)} ${r.pos} ${r.team}  total ${r.totalFpts}  avg ${r.avgFpts} (#${r.avgRank})  ${r.gp}gp`);
}
const noData = rows.filter((r) => !r.hasData);
if (noData.length) console.log(`\nNo 2026 data (${noData.length}): ${noData.slice(0, 12).map((r) => r.name).join(', ')}${noData.length > 12 ? '…' : ''}`);

function round1(n) { return typeof n === 'number' ? Math.round(n * 10) / 10 : 0; }
function round2(n) { return typeof n === 'number' ? Math.round(n * 100) / 100 : 0; }
function round3(n) { return typeof n === 'number' ? Math.round(n * 1000) / 1000 : 0; }
function slug(name, id) {
  const base = String(name ?? id).toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  return base || `p${id}`;
}
